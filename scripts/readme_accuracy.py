"""Write README's accuracy table from the models' own metrics files, so the
README can't keep quoting numbers from an older model.

    python scripts/readme_accuracy.py           rewrite the block in README.md
    python scripts/readme_accuracy.py --check   exit 1 if README is out of date

The block sits between the two ACCURACY markers in README.md. Standard library
only. The weekly retrain runs it after refitting blends and odds.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SAVED = ROOT / "src" / "models" / "saved"
README = ROOT / "README.md"
START, END = "<!-- ACCURACY:START (generated by scripts/readme_accuracy.py) -->", "<!-- ACCURACY:END -->"
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()


def _metrics(target: str) -> dict:
    return json.loads((SAVED / f"{target}_metrics.json").read_text(encoding="utf-8"))


def _window(evaluation: str) -> tuple[int, str]:
    """(races, "Jul 2024 → Oct 2026") from a metrics file's evaluation sentence."""
    n = int(evaluation.split()[0])
    dates = re.findall(r"(\d{4})-(\d{2})-\d{2}", evaluation)
    span = " → ".join(f"{MONTHS[int(m) - 1]} {y}" for y, m in dates[:2])
    return n, span


def block() -> str:
    finish, quali, gap = _metrics("finish_position"), _metrics("qualifying"), _metrics("race_time")
    odds = json.loads((SAVED / "pl_calibration.json").read_text(encoding="utf-8"))["checks"]["race_post_quali"]
    f, q, g = finish["stages"]["post_quali"], quali["stages"]["post_practice"], gap["stages"]["post_quali"]
    (nf, sf), (nq, sq), (ng, sg) = _window(finish["evaluation"]), _window(quali["evaluation"]), _window(gap["evaluation"])
    rows = [
        ("Finishing position *(after quali)*", f"**{f['mae']:.2f}** places", f"{f['baseline_mae']:.2f} · finish where you qualified", f"{nf} races, {sf}"),
        ("Qualifying gap *(after practice)*", f"**{q['mae']:.2f}%** of a lap", f"{q['baseline_mae']:.2f}% · team's recent gap", f"{nq} races, {sq}"),
        ("Gap to winner *(after quali)*", f"**{g['mae']:.2f}%** of race time", f"{g['baseline_mae']:.2f}% · typical past gap", f"{ng} races, {sg}"),
        ("Win odds *(Brier, after quali)*", f"**{odds['brier']['win']:.3f}**", f"{odds['brier_if_guessing_evenly']['win']:.3f} · everyone equal",
         f"{odds['held_out_races']} races"),
    ]
    lines = [START, "", "| Prediction | Model | Simple guess | Races it never saw |", "|---|---|---|---|"]
    lines += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in rows]
    lines += ["", f"_Models trained {finish['trained_at'][:10]} on data through {finish['data_through']}. "
                  "Lower is better for every number._", "", END]
    return "\n".join(lines)


def updated(text: str) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"README.md has no {START} ... {END} block")
    return pattern.sub(lambda _: block(), text)


def main() -> None:
    text = README.read_text(encoding="utf-8")
    new = updated(text)
    if "--check" in sys.argv:
        if new != text:
            raise SystemExit("README.md's accuracy table is out of date: run python scripts/readme_accuracy.py")
        print("README accuracy table is up to date")
        return
    README.write_text(new, encoding="utf-8")
    print("README accuracy table written")


if __name__ == "__main__":
    main()
